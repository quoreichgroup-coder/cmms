package com.grash.service;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.grash.repository.PartQuantityRepository;
import org.junit.jupiter.api.Test;

import java.io.InputStream;
import java.util.List;

import static org.junit.jupiter.api.Assertions.*;
import static org.mockito.Mockito.*;

/**
 * The web designer's PO/PR starter layouts (portrait and landscape), exported by
 * frontend/scripts/pdfme-document-profiles.test.cjs, must pass the real server validation:
 * a user creating a visual PO/PR template must never be refused on the first save.
 */
class PdfmeProcurementStarterValidationTest {

    private final DocumentDataProviderRegistry registry = mock(DocumentDataProviderRegistry.class);
    private final PdfmeTemplateConfigurationValidator validator = new PdfmeTemplateConfigurationValidator(registry);

    PdfmeProcurementStarterValidationTest() {
        when(registry.require("PURCHASE_ORDER")).thenReturn(new PurchaseOrderDocumentDataProvider(
                mock(PartQuantityRepository.class), mock(ProcurementApprovalPrintService.class),
                mock(DocumentLogoService.class), mock(DocumentContextResolver.class)));
        when(registry.require("PURCHASE_REQUISITION")).thenReturn(new PurchaseRequisitionDocumentDataProvider(
                mock(ProcurementApprovalPrintService.class), mock(DocumentLogoService.class),
                mock(DocumentContextResolver.class)));
    }

    private JsonNode fixture() throws Exception {
        try (InputStream input = getClass().getResourceAsStream("/pdfme/procurement-starters.json")) {
            assertNotNull(input, "fixture generated by the frontend profile test");
            return new ObjectMapper().readTree(input);
        }
    }

    @Test
    void webStartersAreAcceptedInPortraitAndLandscape() throws Exception {
        JsonNode starters = fixture();
        for (String provider : List.of("PURCHASE_ORDER", "PURCHASE_REQUISITION")) {
            for (String orientation : List.of("portrait", "landscape")) {
                JsonNode template = starters.path(provider).path(orientation);
                assertFalse(template.isMissingNode(), provider + " " + orientation + " starter is exported");
                assertDoesNotThrow(() -> validator.validate(template, provider, provider),
                        provider + " " + orientation + " starter must be valid");
                List<String> bindings = validator.dataBindings(template);
                assertTrue(bindings.contains("company.logo"), provider + " prints the logo");
            }
        }
    }
}
